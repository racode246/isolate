import { existsSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { git, makeRepo, read, run, snapshot } from "./helpers.js";

const GITIGNORE = ".env\n.env.*\n.isolate-*\n";

describe("edge cases", () => {
  it("restores an .env without a trailing newline exactly", async () => {
    const root = makeRepo({
      tracked: { ".gitignore": GITIGNORE, "compose.yml": 'services:\n  web:\n    ports:\n      - "${WEB_PORT:-3000}:80"\n' },
      untracked: { ".env": "NAME=x" },
    });
    const before = snapshot(root);
    expect((await run(root, ["apply"])).code).toBe(0);
    expect(read(root, ".env")).toMatch(/^NAME=x\nWEB_PORT=\d+\nCOMPOSE_PROJECT_NAME=app-main\n$/);
    expect((await run(root, ["reset"])).code).toBe(0);
    expect(snapshot(root)).toEqual(before);
  });

  it("keeps CRLF line endings and restores them", async () => {
    const root = makeRepo({ tracked: { ".gitignore": GITIGNORE }, untracked: { ".env": "PORT=3000\r\nCOMPOSE_PROJECT_NAME=old\r\n" } });
    const before = snapshot(root);
    expect((await run(root, ["apply"])).code).toBe(0);
    expect(read(root, ".env")).toMatch(/^PORT=\d+\r\nCOMPOSE_PROJECT_NAME=app-main\r\n$/);
    expect((await run(root, ["reset"])).code).toBe(0);
    expect(snapshot(root)).toEqual(before);
  });

  it("resets a checkout applied by the original isolate.sh", async () => {
    const root = makeRepo({
      tracked: { ".gitignore": GITIGNORE },
      untracked: {
        ".env": "PORT=3460\nAPI_PORT=4460\nCOMPOSE_PROJECT_NAME=app-main\nKEEP=1\n",
        ".isolate-ports.env": "# Generated by isolate.sh — do not commit.\nISOLATE_NAME=main\nCOMPOSE_PROJECT_NAME=app-main\nPORT_3000=3460\nPORT_4000=4460\n",
        ".isolate-compose.override.yml": "services: {}\n",
        ".isolate-manifest":
          "# Generated by isolate.sh — do not commit.\n# What apply changed in this checkout (consumed by reset).\nrewritten .env\nkey-added .env COMPOSE_PROJECT_NAME\ngenerated .isolate-compose.override.yml\ngenerated .isolate-ports.env\n",
      },
    });
    const r = await run(root, ["reset"]);
    expect(r.code, r.stderr).toBe(0);
    expect(read(root, ".env")).toBe("PORT=3000\nAPI_PORT=4000\nKEEP=1\n");
    for (const f of [".isolate-ports.env", ".isolate-compose.override.yml", ".isolate-manifest"]) {
      expect(existsSync(join(root, f))).toBe(false);
    }
  });

  it("skips port ranges and malformed compose files with a warning", async () => {
    const root = makeRepo({
      tracked: {
        ".gitignore": GITIGNORE,
        "compose.yml": 'services:\n  web:\n    ports:\n      - "3000-3005:3000-3005"\n      - "${WEB_PORT:-4000}:80"\n',
        "compose.override.yml": "services: [unclosed\n",
      },
    });
    const r = await run(root, ["apply", "--json"]);
    expect(r.code, r.stderr).toBe(0);
    expect(r.stderr).toMatch(/3000-3005/);
    expect(r.stderr).toMatch(/compose\.override\.yml: cannot parse YAML/);
    expect(JSON.parse(r.stdout).ports.map((p: { from: number }) => p.from)).toEqual([4000]);
    expect(git(root, "status", "--porcelain")).toBe("");
  });
});
